#!/usr/bin/env bun
/**
 * Generate the Postgres baseline (`pg-migrations/baseline.generated.ts`) from a
 * live SQLite database.
 *
 * Usage:
 *   bun run scripts/generate-pg-baseline.ts --db <path-to-sqlite-db>
 *   bun run scripts/generate-pg-baseline.ts            # migrate a temp workspace
 *
 * With no `--db`, a throwaway workspace is created and `initializeDb()` runs the
 * full SQLite migration chain to produce a fully-migrated database, which is
 * then introspected. That is the faithful source: the baseline reflects the DDL
 * the migrations actually produce, not the (incomplete) `schema/*.ts` files.
 *
 * The output is committed; regenerating it is part of the port's maintenance.
 */

import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Database } from "bun:sqlite";

import {
  buildBaselineStatements,
  deriveTypeOverrides,
  EXCLUDED_TABLES,
} from "../src/persistence/pg-migrations/baseline.js";
import { introspectSqlite } from "../src/persistence/pg-migrations/sqlite-model.js";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(
  here,
  "..",
  "src",
  "persistence",
  "pg-migrations",
  "baseline.generated.ts",
);

function argValue(flag: string): string | undefined {
  const index = process.argv.indexOf(flag);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

/** Migrate a throwaway workspace and return the four SQLite DB paths. */
async function migratedDbPaths(): Promise<{
  paths: string[];
  cleanup: () => void;
}> {
  const root = mkdtempSync(join(tmpdir(), "vellum-pg-baseline-"));
  const workspace = join(root, "workspace");
  mkdirSync(workspace);
  process.env.VELLUM_WORKSPACE_DIR = workspace;
  process.env.VELLUM_PLATFORM_URL = "https://test-platform.vellum.ai";

  const { initializeDb } = await import("../src/persistence/db-init.js");
  const { getDbPath } = await import("../src/util/platform.js");
  const { getLogsDbPath } = await import("../src/util/logs-db-path.js");
  const { getMemoryDbPath } = await import("../src/util/memory-db-path.js");
  const { getTelemetryDbPath } =
    await import("../src/util/telemetry-db-path.js");
  await initializeDb();
  return {
    paths: [
      getDbPath(),
      getLogsDbPath(),
      getMemoryDbPath(),
      getTelemetryDbPath(),
    ],
    cleanup: () => {
      try {
        rmSync(root, { recursive: true, force: true });
      } catch {
        /* best-effort */
      }
    },
  };
}

/**
 * Merge the tables of every SQLite database into one model. The port lands all
 * four databases in a single Postgres database, so the baseline is their union.
 * A table name appearing in more than one database is a real conflict (the
 * consolidated database cannot hold two shapes) and is reported.
 */
function mergeSchemas(paths: string[]) {
  const tables = new Map<
    string,
    ReturnType<typeof introspectSqlite>["tables"][number]
  >();
  const seenIn = new Map<string, string>();
  for (const path of paths) {
    let db: Database;
    try {
      db = new Database(path, { readonly: true });
    } catch {
      console.warn(`skipping missing database: ${path}`);
      continue;
    }
    const model = introspectSqlite(db);
    db.close();
    for (const table of model.tables) {
      const prior = seenIn.get(table.name);
      if (prior) {
        console.warn(
          `table "${table.name}" appears in both ${prior} and ${path}; keeping the first`,
        );
        continue;
      }
      seenIn.set(table.name, path);
      tables.set(table.name, table);
    }
  }
  return { tables: [...tables.values()] };
}

async function main(): Promise<void> {
  const explicit = argValue("--db");
  const migrated = explicit ? null : await migratedDbPaths();
  const paths = explicit ? [explicit] : migrated!.paths;

  try {
    const model = mergeSchemas(paths);

    const statements = buildBaselineStatements(model, {
      excludeTables: EXCLUDED_TABLES,
      pgTypeOverrides: deriveTypeOverrides(),
    });
    const tableNames = model.tables
      .map((table) => table.name)
      .filter((name) => !EXCLUDED_TABLES.some((pattern) => pattern.test(name)))
      .sort();

    const body = [
      "/**",
      " * AUTO-GENERATED by `scripts/generate-pg-baseline.ts`. Do not edit by hand.",
      " *",
      ` * Source: the effective SQLite schema of a fully-migrated database`,
      ` * (${tableNames.length} tables across the main/logs/memory/telemetry DBs;`,
      ` * llm/compaction logs excluded).`,
      " */",
      "",
      `export const BASELINE_TABLES: readonly string[] = ${JSON.stringify(tableNames, null, 2)};`,
      "",
      `export const BASELINE_STATEMENTS: readonly string[] = [`,
      statements.map((s) => "  " + JSON.stringify(s)).join(",\n"),
      "];",
      "",
    ].join("\n");

    writeFileSync(OUT, body);
    console.log(
      `wrote ${OUT}: ${tableNames.length} tables, ${statements.length} statements`,
    );
  } finally {
    migrated?.cleanup();
  }
}

await main();
