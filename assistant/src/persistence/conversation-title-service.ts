// ── Placeholder / loading state ──────────────────────────────────────

export const GENERATING_TITLE = MESSAGE_KEYS.CONVERSATION_TITLE_GENERATING;
const UNTITLED_FALLBACK = MESSAGE_KEYS.CONVERSATION_TITLE_UNTITLED;

// ── `conversations.isAutoTitle` values ───────────────────────────────
//
// Most readers treat the column as a boolean ("not user-set"); the two
// distinct non-zero values let the title pipeline tell HOW a title was set.

/** Title was generated by an LLM from conversation content. */
export const AUTO_TITLE_LLM = 1;
/**
 * Title was derived deterministically from bootstrap context — no LLM call,
 * no user input. Unlike LLM titles, these stay replaceable: the first
 * genuine user message in the conversation upgrades them to an LLM title
 * (see `canReplaceTitle`).
 */
export const AUTO_TITLE_DETERMINISTIC = 2;

/**
 * Whether auto-generation may overwrite the conversation's current title.
 * True for placeholder/system titles and for deterministic bootstrap titles
 * (`AUTO_TITLE_DETERMINISTIC`); false for user-set custom titles and titles
 * already generated by an LLM.
 */
function canReplaceTitle(conversation: {
  title: string | null;
  isAutoTitle: number;
}): boolean {
  return (
    isReplaceableTitle(conversation.title) ||
    conversation.isAutoTitle === AUTO_TITLE_DETERMINISTIC
  );
}

/**
 * Derive a deterministic title from bootstrap context without an LLM call.
 * Used for background/system conversations (heartbeat runs, scheduled jobs,
 * subagents, retrospectives) where an LLM-generated title is not worth the
 * tokens — the bootstrap `systemHint` already names the work. Persist it
 * with `AUTO_TITLE_DETERMINISTIC` so a later genuine user message can still
 * upgrade it to an LLM title.
 */
export function deriveDeterministicTitle(context: TitleContext): string {
  const base = deriveFallbackTitle(context) ?? UNTITLED_FALLBACK;
  return truncateTitle(base.replace(/\s+/g, " ").trim());
}

/**
 * Apply a deterministic title to a conversation, but only while its current
 * title is still a replaceable placeholder — never clobbering a user or LLM
 * title. For conversations that will never run an agent turn (so neither the
 * `user-prompt-submit` nor `stop` title hook ever fires), e.g. a floor-denied
 * inbound whose only content is a guardian access-request card: without this
 * the sidebar shows a permanent "Generating title…". Persisted as
 * `AUTO_TITLE_DETERMINISTIC` so a later genuine turn can still upgrade it, and
 * broadcast so connected clients converge. Returns the title the conversation
 * carries once it settles, and whether this call is what set it.
 */
export async function applyDeterministicTitleIfReplaceable(
  conversationId: string,
  title: string,
): Promise<{ title: string; updated: boolean }> {
  const conversation = await getConversation(conversationId);
  if (conversation && !isReplaceableTitle(conversation.title)) {
    return { title: conversation.title!, updated: false };
  }
  const cleaned =
    truncateTitle(title.replace(/\s+/g, " ").trim()) || UNTITLED_FALLBACK;
  await updateConversationTitle(
    conversationId,
    cleaned,
    AUTO_TITLE_DETERMINISTIC,
  );
  publishConversationTitleChanged(conversationId, cleaned);
  return { title: cleaned, updated: true };
}

// ── Title generation ─────────────────────────────────────────────────

export interface GenerateTitleParams {
  conversationId: string;
  /** Provider to use for LLM call. Falls back to getConfiguredProvider(). */
  provider?: Provider;
  /** Context about how/where the conversation was created. */
  context?: TitleContext;
  /** User message text (first turn). */
  userMessage?: string;
  /** Assistant response text (first turn). */
  assistantResponse?: string;
  /** Abort signal. */
  signal?: AbortSignal;
  /**
   * First-pass group filing: offer the model the existing custom groups and
   * let it file the conversation into one via the tool's optional `group_id`
   * argument. Same one-shot, confidence-gated guards as the turn-3 pass.
   */
  allowGroupAssignment?: boolean;
}

/**
 * Generate a conversation title via LLM and persist it, but only if the
 * current title is still replaceable (safe overwrite policy).
 */
export async function generateAndPersistConversationTitle(
  params: GenerateTitleParams,
): Promise<{ title: string; updated: boolean }> {
  const {
    conversationId,
    context,
    userMessage,
    assistantResponse,
    allowGroupAssignment,
    signal,
  } = params;

  // Check current title is replaceable
  const conversation = await getConversation(conversationId);
  if (conversation && !canReplaceTitle(conversation)) {
    return { title: conversation.title!, updated: false };
  }

  const prompt = await buildTitlePrompt(
    context,
    userMessage,
    assistantResponse,
    allowGroupAssignment,
  );
  // A prompt carrying no text gives the model nothing to title from: an
  // image-only turn submits an empty prompt, and the forced title tool makes
  // the model fabricate a topic rather than decline.
  if (prompt.trim() === "") {
    return await settleForDeterministicTitle(conversationId, context);
  }

  const provider =
    params.provider ?? (await getConfiguredProvider("conversationTitle"));
  if (!provider) {
    logRetryableFallback(params, "no_provider");
    return await settleForDeterministicTitle(conversationId, context);
  }

  const { title, groupId, confidence } = await callTitleLabelLLM(
    provider,
    prompt,
    conversationId,
    allowGroupAssignment === true,
    signal,
  );
  if (title) {
    // Re-check replaceability before persisting (race guard)
    const current = await getConversation(conversationId);
    if (current && !canReplaceTitle(current)) {
      return { title: current.title!, updated: false };
    }

    await updateConversationTitle(conversationId, title, AUTO_TITLE_LLM);
    publishConversationTitleChanged(conversationId, title);
    log.info({ conversationId, title }, "Auto-generated conversation title");
    await maybeAssignConversationGroup(conversationId, groupId, confidence);
    return { title, updated: true };
  }

  logRetryableFallback(params, "empty_output");
  return await settleForDeterministicTitle(conversationId, context);
}

/**
 * Settle a conversation on a title derived from its creation context, for the
 * outcomes that produce no LLM title: the provider is unreachable, the model
 * declined, or the prompt had no text to title from. Clearing a loading
 * placeholder is worth doing; overwriting a title that already names the work
 * (a background job's bootstrap title) is not, which is why this defers to
 * `applyDeterministicTitleIfReplaceable` rather than writing directly.
 */
async function settleForDeterministicTitle(
  conversationId: string,
  context: TitleContext | undefined,
): Promise<{ title: string; updated: boolean }> {
  return await applyDeterministicTitleIfReplaceable(
    conversationId,
    deriveFallbackTitle(context) ?? UNTITLED_FALLBACK,
  );
}

// ── Serial title-generation queue ────────────────────────────────────

/**
 * Each title generation makes an LLM call. Without serialization, burst
 * conversation creation (e.g. 5 new chats in quick succession) fires N
 * concurrent requests that can hit provider rate limits or contend for
 * API capacity, causing later calls to time out and fall back to
 * the untitled catalog key.
 *
 * A serial queue ensures at most one title-generation LLM call is
 * in-flight at a time. Each call is lightweight (~1–3 s for a ≤5-word
 * title), so the added serial latency is modest and invisible to the
 * user (the UI shows "Generating title…" as a placeholder during the
 * wait). Both initial generation and second-pass regeneration share
 * this queue since they hit the same provider.
 */
export const titleMutex = new Mutex();

/**
 * Fire-and-forget wrapper for title generation. Failures are logged
 * but do not propagate. On failure, replaces loading placeholder with
 * a retryable fallback title so loading state is never permanent.
 *
 * Calls are serialized via {@link titleMutex} so burst conversation
 * creation does not overwhelm the LLM provider.
 */
export function queueGenerateConversationTitle(
  params: GenerateTitleParams,
): void {
  void titleMutex
    .withLock(async () => {
      await generateAndPersistConversationTitle(params);
    })
    .catch(async (err) => {
      log.warn(
        retryableFallbackLogFields(params, "generation_error", err),
        "Conversation title generation used retryable fallback",
      );
      // Replace loading placeholder with a retryable fallback.
      try {
        const conversation = await getConversation(params.conversationId);
        if (conversation && isReplaceableTitle(conversation.title)) {
          const fallback =
            deriveFallbackTitle(params.context) ?? UNTITLED_FALLBACK;
          await updateConversationTitle(
            params.conversationId,
            fallback,
            AUTO_TITLE_DETERMINISTIC,
          );
          publishConversationTitleChanged(params.conversationId, fallback);
        }
      } catch {
        // Best-effort
      }
    });
}

// ── Title regeneration (second pass) ─────────────────────────────────

export interface RegenerateTitleParams {
  conversationId: string;
  provider?: Provider;
  signal?: AbortSignal;
  /**
   * Limit regeneration to placeholder or deterministic titles. Used for retrying
   * failed initial generation without racing against a successful initial title.
   */
  onlyIfReplaceable?: boolean;
  /**
   * Turn-3 second pass only: also offer the model the existing custom groups
   * and let it file the conversation into one via the tool's optional
   * `group_id` argument. Group assignment is one-shot: it only happens here,
   * and only while the conversation has never been grouped.
   */
  allowGroupAssignment?: boolean;
}

/**
 * Re-generate a conversation title using the last 3 stored messages.
 * Only fires when the current title was auto-generated (isAutoTitle = 1).
 * Skips if the user has manually renamed the conversation.
 */
export async function regenerateConversationTitle(
  params: RegenerateTitleParams,
): Promise<{ title: string; updated: boolean }> {
  const { conversationId, onlyIfReplaceable, allowGroupAssignment, signal } =
    params;

  const conversation = await getConversation(conversationId);
  if (!conversation || !conversation.isAutoTitle) {
    return { title: conversation?.title ?? UNTITLED_FALLBACK, updated: false };
  }
  if (onlyIfReplaceable && !canReplaceTitle(conversation)) {
    return { title: conversation.title ?? UNTITLED_FALLBACK, updated: false };
  }

  const provider =
    params.provider ?? (await getConfiguredProvider("conversationTitle"));
  if (!provider) {
    return { title: conversation.title ?? UNTITLED_FALLBACK, updated: false };
  }

  const allMessages = await getMessages(conversationId);
  const recentMessages = allMessages.slice(-3);
  if (recentMessages.length === 0) {
    return { title: conversation.title ?? UNTITLED_FALLBACK, updated: false };
  }

  const prompt = await buildRegenerationPrompt(recentMessages, {
    currentTitle: conversation.title,
    firstMessage: allMessages[0],
    allowGroupAssignment,
  });
  // Skip the LLM call if no messages yielded extractable text — the prompt
  // would be just the "Recent messages:" header, and the model tends to
  // fabricate a meta-title about the emptiness rather than decline.
  if (!/\n(?:User|Assistant): /.test(prompt)) {
    return { title: conversation.title ?? UNTITLED_FALLBACK, updated: false };
  }
  const { title, groupId, confidence } = await callTitleLabelLLM(
    provider,
    prompt,
    conversationId,
    allowGroupAssignment === true,
    signal,
  );
  if (title) {
    // Re-check isAutoTitle before persisting (race guard against manual rename)
    const current = await getConversation(conversationId);
    if (
      !current ||
      !current.isAutoTitle ||
      (onlyIfReplaceable && !canReplaceTitle(current))
    ) {
      return { title: current?.title ?? UNTITLED_FALLBACK, updated: false };
    }

    await updateConversationTitle(conversationId, title, AUTO_TITLE_LLM);
    publishConversationTitleChanged(conversationId, title);
    log.info(
      { conversationId, title },
      "Re-generated conversation title (second pass)",
    );
    await maybeAssignConversationGroup(conversationId, groupId, confidence);
    return { title, updated: true };
  }

  return { title: conversation.title ?? UNTITLED_FALLBACK, updated: false };
}

/**
 * Fire-and-forget wrapper for title regeneration.
 *
 * Serialized via the same {@link titleMutex} as initial generation.
 */
export function queueRegenerateConversationTitle(
  params: RegenerateTitleParams,
): void {
  void titleMutex
    .withLock(async () => {
      await regenerateConversationTitle(params);
    })
    .catch((err) => {
      log.warn(
        { err, conversationId: params.conversationId },
        "Failed to regenerate conversation title (non-fatal)",
      );
    });
}

// ── Internal helpers ─────────────────────────────────────────────────

/**
 * Dedicated system prompt for title generation. Replaces the default
 * assistant system prompt that btw-sidechain would otherwise inject,
 * which caused the model to respond to the conversation content instead
 * of titling it.
 *
 * When `groupAssignment` is set (the turn-3 second pass), the prompt also
 * covers the optional `group_id` tool argument: the model may file the
 * conversation into an existing group, but only when it is certain.
 */
function buildTitleSystemPrompt(options?: {
  groupAssignment?: boolean;
}): string {
  const lines = [
    "You generate ultra-concise conversation titles. Output ONLY the title text — no explanation, no quotes, no markdown, no preamble.",
    "",
    "Rules:",
    "- 2–5 words maximum. Titles longer than 5 words are unacceptable — ruthlessly compress to a short noun phrase",
    "- 40 characters absolute maximum — if your title exceeds 40 characters it will be truncated and look broken",
    "- Summarize only the TOPIC, not the request or instructions",
    "- Noun phrases are ideal (e.g. 'Auth Middleware Rewrite', 'Docker Volume Mounts', 'Onboarding Flow')",
    "- Think: what would make a scannable sidebar label?",
    "- Do NOT echo back what the user asked you to do",
    "- Do NOT respond to the conversation content",
    "- Write the title in the same language as the conversation content",
    "- Do NOT assess feasibility or comment on capabilities",
    "- The conversation's real topic lives in the FIRST user message and the current title; the recent messages are only the latest activity. Refine the current title, never pivot it onto whatever the last few messages happened to discuss",
    "- If input is sparse or references external context, extract a topic from the words that ARE present (e.g. 'so about that t-shirt...' → 'T-Shirt Discussion'). Never describe the absence, emptiness, or insufficiency of context — titles like 'Missing Context', 'Unclear Request', 'No Topic' are forbidden",
  ];
  if (options?.groupAssignment) {
    lines.push(
      "",
      "Grouping rules:",
      "- The tool also accepts an optional `group_id` argument, taken from the list of existing groups in the prompt, plus a `confidence` score (0-100) for that choice",
      "- `confidence` is your honest certainty that the chosen group is the right one for this conversation as a whole (a project, client, or topic it is actually about). The group is applied only when confidence is 80 or higher; below that the assignment is discarded, so a low-confidence guess is never better than omitting `group_id`",
      "- Include `group_id` only when genuinely confident; when in any doubt, omit both arguments. An ungrouped conversation is always acceptable",
      "- Never invent or guess a group id; use only an id from the list, exactly as written",
      "- If the list of existing groups is empty or none clearly applies, omit `group_id`",
    );
  }
  return lines.join("\n");
}

const TITLE_TOOL_NAME = "record_conversation_title";

/**
 * Tool the title model is forced to call. Constraining the output to a single
 * `title` argument keeps weak/fast models (e.g. Haiku-class title models) from
 * "thinking aloud" or continuing the conversation in the response text —
 * failure modes that otherwise get captured verbatim as the title
 * (e.g. "I need to generate a…", "I'll work through these files…").
 */
const TITLE_TOOL: ShortLabelTool = {
  name: TITLE_TOOL_NAME,
  description:
    "Record the conversation's title. Call this exactly once with a short noun phrase naming the TOPIC — never a sentence, a reply, or any preamble.",
  argument: "title",
  argumentDescription:
    "2–5 words, 40 characters max. A scannable sidebar label naming the topic (e.g. 'Auth Middleware Rewrite', 'Docker Volume Mounts'). No quotes, markdown, or trailing punctuation.",
  optionalArguments: [
    {
      name: "group_id",
      description:
        "Optional. The id of ONE existing group this conversation clearly belongs to (from the list in the prompt). Omit when no listed group clearly applies.",
    },
    {
      name: "confidence",
      type: "number",
      description:
        "Required whenever group_id is given: your certainty (0-100) that the chosen group is correct for this conversation. Be honest; the group is applied only at 80 or higher.",
    },
  ],
};

/**
 * Minimum model-reported confidence (0-100) for an auto group assignment to
 * be applied. Below this the assignment is discarded and the conversation
 * stays ungrouped. A wrong filing is worse than no filing.
 */
const GROUP_ASSIGNMENT_MIN_CONFIDENCE = 80;

/**
 * Run the title LLM call through the shared forced-tool label helper. Same
 * forced tool for both the first pass and the turn-3 regeneration; when
 * `groupAssignment` is set the grouping rules are enabled in the system
 * prompt and the optional `group_id`/`confidence` arguments are read.
 * `title` is "" when the model declines or misbehaves; callers fall back to
 * a deterministic title. `groupId`/`confidence` are undefined when the model
 * omitted them or the caller did not enable group assignment.
 */
async function callTitleLabelLLM(
  provider: Provider,
  prompt: string,
  conversationId: string,
  groupAssignment: boolean,
  signal?: AbortSignal,
): Promise<{ title: string; groupId?: string; confidence?: number }> {
  const result = await requestStructuredLabel({
    provider,
    callSite: "conversationTitle",
    conversationId,
    systemPrompt: buildTitleSystemPrompt({ groupAssignment }),
    prompt,
    tool: TITLE_TOOL,
    timeoutMs: 15_000,
    maxTokens: 256,
    signal,
  });
  const rawTitle = result[TITLE_TOOL.argument];
  const title = typeof rawTitle === "string" ? rawTitle : "";
  if (!title) {
    return { title: "" };
  }
  if (!groupAssignment) {
    return { title };
  }
  const rawGroupId = result.group_id;
  const groupId =
    typeof rawGroupId === "string" && rawGroupId.trim()
      ? rawGroupId.trim()
      : undefined;
  const rawConfidence = result.confidence;
  const confidence =
    typeof rawConfidence === "number" &&
    Number.isFinite(rawConfidence) &&
    rawConfidence >= 0 &&
    rawConfidence <= 100
      ? rawConfidence
      : undefined;
  return { title, groupId, confidence };
}

/**
 * One-shot group assignment shared by the first title pass and the turn-3
 * regeneration. Files the conversation into `groupId` only when every guard
 * passes: the model reported `confidence` at or above
 * {@link GROUP_ASSIGNMENT_MIN_CONFIDENCE}, the id names an existing custom
 * (non-system) group, and the conversation has never been grouped (`group_id`
 * NULL or the Recents sentinel). A manually filed conversation is never
 * re-filed, a low-confidence guess is discarded, and a model-hallucinated id
 * is rejected against the group table. Best-effort: failures are logged and
 * leave the conversation ungrouped.
 */
async function maybeAssignConversationGroup(
  conversationId: string,
  groupId: string | undefined,
  confidence: number | undefined,
): Promise<void> {
  if (!groupId) {
    return;
  }
  if (
    confidence === undefined ||
    confidence < GROUP_ASSIGNMENT_MIN_CONFIDENCE
  ) {
    log.info(
      { conversationId, groupId, confidence },
      "Ignored group assignment: below confidence threshold",
    );
    return;
  }
  try {
    const group = (await listGroups()).find(
      (g) => g.id === groupId && !g.isSystemGroup,
    );
    if (!group) {
      log.info(
        { conversationId, groupId },
        "Ignored group assignment: unknown or system group id",
      );
      return;
    }
    const meta = (await getDisplayMetaForConversations([conversationId])).get(
      conversationId,
    );
    const currentGroupId = meta?.groupId ?? null;
    if (currentGroupId !== null && currentGroupId !== UNGROUPED_GROUP_ID) {
      log.info(
        { conversationId, groupId, currentGroupId },
        "Ignored group assignment: conversation already grouped",
      );
      return;
    }
    await batchSetConversationPlacement([
      { id: conversationId, groupId: group.id },
    ]);
    publishConversationListAndMetadataChanged("reordered", [conversationId]);
    log.info(
      { conversationId, groupId: group.id, groupName: group.name, confidence },
      "Auto-assigned conversation group",
    );
  } catch (err) {
    log.warn(
      { err, conversationId, groupId },
      "Group assignment during title regeneration failed (non-fatal)",
    );
  }
}

async function buildTitlePrompt(
  context?: TitleContext,
  userMessage?: string,
  assistantResponse?: string,
  allowGroupAssignment?: boolean,
): Promise<string> {
  const parts: string[] = [];

  if (context) {
    const hints: string[] = [];
    if (context.sourceChannel) {
      hints.push(`Channel: ${context.sourceChannel}`);
    }
    if (context.displayName) {
      hints.push(`User: ${context.displayName}`);
    }
    if (context.systemHint) {
      hints.push(`Context: ${context.systemHint}`);
    }
    if (context.uxBrief) {
      hints.push(`Brief: ${context.uxBrief}`);
    }
    if (context.metadataHints?.length) {
      hints.push(`Hints: ${context.metadataHints.join(", ")}`);
    }
    if (hints.length > 0) {
      parts.push("Metadata:", ...hints, "");
    }
  }

  // Trim after stripping so a turn carrying nothing but thinking tags reads as
  // no text at all, the same as an image-only or whitespace-only prompt.
  const userText = userMessage ? stripThinkingTags(userMessage).trim() : "";
  if (userText) {
    parts.push(`User: ${userText}`);
  }
  const assistantText = assistantResponse
    ? stripThinkingTags(assistantResponse).trim()
    : "";
  if (assistantText) {
    parts.push(`Assistant: ${assistantText}`);
  }

  if (allowGroupAssignment) {
    const customGroups = (await listGroups()).filter((g) => !g.isSystemGroup);
    parts.push("", "Existing groups:");
    if (customGroups.length === 0) {
      parts.push("(none)");
    } else {
      for (const group of customGroups) {
        parts.push(`- ${group.name} (id: ${group.id})`);
      }
    }
  }

  return parts.join("\n");
}

function titleGenerationLogFields(params: GenerateTitleParams) {
  return {
    conversationId: params.conversationId,
    contextOrigin: params.context?.origin,
    hasContext: Boolean(params.context),
    userMessageLength: params.userMessage?.length ?? 0,
    assistantResponseLength: params.assistantResponse?.length ?? 0,
  };
}

type TitleGenerationFallbackReason =
  | "no_provider"
  | "empty_output"
  | "generation_error";

function retryableFallbackLogFields(
  params: GenerateTitleParams,
  reason: TitleGenerationFallbackReason,
  err?: unknown,
): Record<string, unknown> {
  const fields: Record<string, unknown> = {
    ...titleGenerationLogFields(params),
    reason,
    fallbackSource: params.context ? "context" : "untitled",
  };
  if (err) {
    fields.err = err;
  }
  return fields;
}

function logRetryableFallback(
  params: GenerateTitleParams,
  reason: TitleGenerationFallbackReason,
): void {
  log.warn(
    retryableFallbackLogFields(params, reason),
    "Conversation title generation used retryable fallback",
  );
}

function deriveFallbackTitle(context?: TitleContext): string | null {
  if (!context) {
    return null;
  }
  if (context.systemHint) {
    return context.systemHint;
  }
  if (context.uxBrief) {
    return context.uxBrief;
  }
  return null;
}

/**
 * Extract only human-authored text from stored message content for title
 * generation. Unlike extractTextFromStoredMessageContent (which includes
 * tool metadata like "Tool use (...): {...}"), this only extracts:
 * - `text` blocks (the actual conversation content)
 * - `tool_result` string content (topical signal from tool responses)
 *   — web_search_tool_result is skipped (structured search data, not topical)
 *
 * Returns empty string for content-block arrays with no extractable text,
 * preventing raw JSON from polluting the title prompt.
 */
function extractTextForTitle(raw: string | Array<{ type: string }>): string {
  try {
    const parsed = Array.isArray(raw) ? raw : JSON.parse(raw);
    if (typeof parsed === "string") {
      return parsed;
    }
    if (!Array.isArray(parsed)) {
      return raw as string;
    }
    const texts: string[] = [];
    for (const block of parsed) {
      if (!block || typeof block !== "object") {
        continue;
      }
      if (block.type === "text" && typeof block.text === "string") {
        texts.push(block.text);
        // guard:allow-tool-result-only — web_search_tool_result has structured
        // search result arrays, not useful for title generation; only plain
        // tool_result string content carries topical signal.
      } else if (block.type === "tool_result") {
        if (typeof block.content === "string") {
          // The delivery tool answers a bare receipt, never anything topical.
          // Titling from it names a gated conversation "Delivery Confirmation"
          // instead of what the user actually asked about.
          if (block.content.trim() !== SEND_USER_MESSAGE_DELIVERED_ACK) {
            texts.push(block.content);
          }
        } else if (Array.isArray(block.content)) {
          for (const nested of block.content) {
            if (
              nested &&
              typeof nested === "object" &&
              nested.type === "text" &&
              typeof nested.text === "string"
            ) {
              texts.push(nested.text);
            }
          }
        }
      }
    }
    return texts.join("\n");
  } catch {
    return Array.isArray(raw) ? "" : raw;
  }
}

async function buildRegenerationPrompt(
  recentMessages: MessageRow[],
  options?: {
    currentTitle?: string | null;
    firstMessage?: MessageRow;
    allowGroupAssignment?: boolean;
  },
): Promise<string> {
  const parts: string[] = [];

  // The first user message carries the conversation's real topic; the recent
  // messages are only the latest activity. Anchoring on both keeps the
  // second-pass title from pivoting onto whatever the last few messages
  // happened to discuss in a long conversation.
  const firstText = options?.firstMessage
    ? stripThinkingTags(
        extractTextForTitle(
          projectPersistedAssistantContent(
            options.firstMessage.content,
            options.firstMessage.metadata,
          ),
        ),
      ).trim()
    : "";
  if (firstText) {
    parts.push("First user message:", `User: ${firstText}`, "");
  }
  if (options?.currentTitle && !isReplaceableTitle(options.currentTitle)) {
    parts.push("Current title:", options.currentTitle, "");
  }

  parts.push("Recent messages:");

  for (const msg of recentMessages) {
    // Read each row the way a user reads it. On a turn that routed its reply
    // through `send_user_message`, the row's plain text is a private
    // scratchpad and the reply is inside the tool call, so titling from the
    // raw row names the conversation after the model's notes.
    const text = extractTextForTitle(
      projectPersistedAssistantContent(msg.content, msg.metadata),
    );
    if (!text) {
      continue;
    }
    const role = msg.role === "user" ? "User" : "Assistant";
    parts.push(`${role}: ${stripThinkingTags(text)}`);
  }

  if (options?.allowGroupAssignment) {
    const customGroups = (await listGroups()).filter((g) => !g.isSystemGroup);
    parts.push("", "Existing groups:");
    if (customGroups.length === 0) {
      parts.push("(none)");
    } else {
      for (const group of customGroups) {
        parts.push(`- ${group.name} (id: ${group.id})`);
      }
    }
  }

  return parts.join("\n");
}
